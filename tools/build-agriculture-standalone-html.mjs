/**
 * 将农业水渠 Demo 打成单文件 HTML（不 fetch / 不引用外部 JSON、embed.js）
 * 用法：node tools/build-agriculture-standalone-html.mjs
 * 输出：agriculture-standalone.html（项目根，双击或 Live Server 均可玩）
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(__dirname, 'agriculture-irrigation-demo.html');
const SEAWED_SRC = path.join(__dirname, 'seaweed-extract-design-overview.html');
const SHOP_JSON = path.join(ROOT, 'data', 'agriculture-seed-shop.json');
const CROP_JSON = path.join(ROOT, 'data', 'agriculture-crop-defs.json');
const SOILS_JSON = path.join(ROOT, 'data', 'agriculture-soils.json');
const OUT = path.join(ROOT, 'agriculture-standalone.html');

if (!fs.existsSync(SRC)) {
  console.error('Missing source:', SRC);
  process.exit(1);
}
if (!fs.existsSync(SHOP_JSON)) {
  console.error('Missing seed shop data:', SHOP_JSON);
  console.error('Run: npm run build:agriculture-crops');
  process.exit(1);
}
if (!fs.existsSync(CROP_JSON)) {
  console.error('Missing crop defs:', CROP_JSON);
  console.error('Run: node tools/gen-agriculture-crop-defs.mjs');
  process.exit(1);
}
if (!fs.existsSync(SOILS_JSON)) {
  console.error('Missing soils:', SOILS_JSON);
  process.exit(1);
}

const shopPayload = JSON.parse(fs.readFileSync(SHOP_JSON, 'utf8'));
const cropPayload = JSON.parse(fs.readFileSync(CROP_JSON, 'utf8'));
const soilsPayload = JSON.parse(fs.readFileSync(SOILS_JSON, 'utf8'));

/** 内嵌到 <script> 时须打断 </script>，否则 HTML 解析器会提前闭合标签、主脚本失效 */
function jsonForInlineScript(value) {
  return JSON.stringify(value).replace(/<\/script/gi, '<\\/script');
}

let html = fs.readFileSync(SRC, 'utf8');

html = html.replace(/<title>[^<]*<\/title>/, '<title>低脂胖生</title>');

html = html.replace(
  /\s*<!-- 种子商店[\s\S]*?<script src="agriculture-crop-defs\.embed\.js"><\/script>\s*/i,
  '\n'
);
html = html.replace(/\s*<script src="agriculture-seed-shop\.embed\.js"><\/script>\s*/gi, '\n');
html = html.replace(/\s*<script src="agriculture-crop-defs\.embed\.js"><\/script>\s*/gi, '\n');

const inlineDataScripts =
  '  <!-- 内嵌农业数据（单文件 Demo；改 data/*.json 后 npm run build:agriculture-crops && 本脚本） -->\n'
  + '  <script>\n'
  + '    window.AGRICULTURE_SEED_SHOP = '
  + jsonForInlineScript(shopPayload)
  + ';\n'
  + '    window.AGRICULTURE_CROP_DEFS = '
  + jsonForInlineScript(cropPayload)
  + ';\n'
  + '    window.AGRICULTURE_SOILS = '
  + jsonForInlineScript(soilsPayload)
  + ';\n'
  + '  </script>\n';

if (!html.includes('window.AGRICULTURE_SEED_SHOP =')) {
  html = html.replace(/<script>\s*\n\s*\(function \(\) \{/, (m) => inlineDataScripts + m);
}

const simpleLoaders =
  '      function loadSeedShopCatalog(done) {\n'
  + '        applySeedShopCatalog(window.AGRICULTURE_SEED_SHOP);\n'
  + '        if (typeof done === "function") done(true);\n'
  + '      }\n'
  + '      function loadCropDefs(done) {\n'
  + '        applyCropDefs(window.AGRICULTURE_CROP_DEFS);\n'
  + '        if (typeof done === "function") done(true);\n'
  + '      }\n';

html = html.replace(/function loadCropDefs\(done\) \{[\s\S]*?\r?\n      \}\r?\n/, '');
html = html.replace(/function loadSeedShopCatalog\(done\) \{[\s\S]*?\r?\n      \}\r?\n/, '');
html = html.replace(/function loadSoilDefs\(done\) \{[\s\S]*?\r?\n      \}\r?\n/, '');
html = html.replace(/\r?\n\s*\/\*\* Live Server[\s\S]*?function projectDataUrl\([^\)]*\) \{[\s\S]*?\r?\n      \}\r?\n/, '\n');
html = html.replace(
  /function listPlantableCropDefsForCell/,
  simpleLoaders
  + '      function loadSoilDefs(done) {\n'
  + '        applySoilDefs(window.AGRICULTURE_SOILS);\n'
  + '        if (typeof done === "function") done(true);\n'
  + '      }\n'
  + '      function listPlantableCropDefsForCell'
);

html = html.replace(
  /fetch\("seaweed-extract-design-overview\.html"\)[\s\S]*?el\.seaweedGuideModal\.hidden = false;\s*\n\s*\}\);/,
  'show(window.SEAWEED_GUIDE_HTML || "");'
);

if (fs.existsSync(SEAWED_SRC)) {
  const seaweedHtml = fs.readFileSync(SEAWED_SRC, 'utf8');
  const guideInject =
    '  <script>window.SEAWEED_GUIDE_HTML = '
    + jsonForInlineScript(seaweedHtml)
    + ';</script>\n';
  if (html.includes('<!-- @build:seaweed-guide-inline -->')) {
    html = html.replace('<!-- @build:seaweed-guide-inline -->', guideInject.trimEnd());
  } else if (!html.includes('window.SEAWEED_GUIDE_HTML =')) {
    html = html.replace(
      /<!-- 内嵌农业数据[\s\S]*?<\/script>\s*/,
      (m) => m + guideInject
    );
  }
}

const banner =
  '<!-- agriculture-standalone.html — AUTO-GENERATED by tools/build-agriculture-standalone-html.mjs — 单文件可离线试玩（含内嵌海藻精设定说明），勿直接改此文件 -->\n';
if (!html.startsWith('<!-- agriculture-standalone')) {
  html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + banner);
}

fs.writeFileSync(OUT, html, 'utf8');

if (!html.includes('window.AGRICULTURE_SEED_SHOP =') || !html.includes('buildGridDom();')) {
  console.error('Build validation failed: main demo script missing or HTML structure broken.');
  console.error('Check jsonForInlineScript() escapes </script> in embedded HTML strings.');
  process.exit(1);
}

function extractScriptBodies(doc) {
  const bodies = [];
  let pos = 0;
  while (true) {
    const open = doc.indexOf('<script', pos);
    if (open < 0) break;
    const openEnd = doc.indexOf('>', open);
    if (openEnd < 0) break;
    const close = doc.indexOf('</script>', openEnd + 1);
    if (close < 0) break;
    bodies.push(doc.slice(openEnd + 1, close));
    pos = close + 9;
  }
  return bodies;
}

const mainScript = extractScriptBodies(html).pop();
if (!mainScript) {
  console.error('Build validation failed: no main script block found.');
  process.exit(1);
}
try {
  // eslint-disable-next-line no-new-func
  new Function(mainScript);
} catch (err) {
  console.error('Build validation failed: main script syntax error:', err.message);
  process.exit(1);
}

const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
console.log(
  'Wrote',
  OUT,
  '(' + kb + ' KB, seeds:',
  shopPayload.seeds.length + ', crops:',
  Object.keys(cropPayload.crops || {}).length + ')'
);
