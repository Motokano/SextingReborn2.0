/**
 * 将农业水渠 Demo 打成单文件 HTML（不 fetch / 不引用外部 JSON、embed.js）
 * 用法：node tools/build-agriculture-standalone-html.mjs
 * 输出：agriculture-standalone.html（项目根，双击或 Live Server 均可玩）
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(__dirname, 'agriculture-irrigation-demo.html');
const SHOP_JSON = path.join(ROOT, 'data', 'agriculture-seed-shop.json');
const CROP_JSON = path.join(ROOT, 'data', 'agriculture-crop-defs.json');
const OUT = path.join(ROOT, 'agriculture-standalone.html');

if (!fs.existsSync(SRC)) {
  console.error('Missing source:', SRC);
  process.exit(1);
}
if (!fs.existsSync(SHOP_JSON)) {
  console.error('Missing seed shop data:', SHOP_JSON);
  console.error('Run: npm run build:agriculture-crops');
  process.exit(1);
}
if (!fs.existsSync(CROP_JSON)) {
  console.error('Missing crop defs:', CROP_JSON);
  console.error('Run: node tools/gen-agriculture-crop-defs.mjs');
  process.exit(1);
}

const shopPayload = JSON.parse(fs.readFileSync(SHOP_JSON, 'utf8'));
const cropPayload = JSON.parse(fs.readFileSync(CROP_JSON, 'utf8'));
let html = fs.readFileSync(SRC, 'utf8');

html = html.replace(/<title>[^<]*<\/title>/, '<title>农业水渠 · 独立 Demo</title>');

html = html.replace(
  /\s*<!-- 种子商店[\s\S]*?<script src="agriculture-crop-defs\.embed\.js"><\/script>\s*/i,
  '\n'
);

const inlineDataScripts =
  '  <!-- 内嵌农业数据（单文件 Demo；改 data/*.json 后 npm run build:agriculture-crops && 本脚本） -->\n'
  + '  <script>\n'
  + '    window.AGRICULTURE_SEED_SHOP = '
  + JSON.stringify(shopPayload)
  + ';\n'
  + '    window.AGRICULTURE_CROP_DEFS = '
  + JSON.stringify(cropPayload)
  + ';\n'
  + '  </script>\n';

if (!html.includes('window.AGRICULTURE_SEED_SHOP =')) {
  html = html.replace(/<script>\s*\n\s*\(function \(\) \{/, (m) => inlineDataScripts + m);
}

const simpleLoaders =
  '      function loadSeedShopCatalog(done) {\n'
  + '        applySeedShopCatalog(window.AGRICULTURE_SEED_SHOP);\n'
  + '        if (typeof done === "function") done(true);\n'
  + '      }\n'
  + '      function loadCropDefs(done) {\n'
  + '        applyCropDefs(window.AGRICULTURE_CROP_DEFS);\n'
  + '        if (typeof done === "function") done(true);\n'
  + '      }\n';

html = html.replace(
  /function loadSeedShopCatalog\(done\) \{[\s\S]*?\n      \}\n      function loadCropDefs\(done\) \{[\s\S]*?\n      \}\n/,
  simpleLoaders
);
html = html.replace(
  /function projectDataUrl\([\s\S]*?function loadSeedShopCatalog\(done\) \{[\s\S]*?\n      \}\n/,
  (m) => {
    const prefix = m.split('function loadSeedShopCatalog')[0];
    return prefix + simpleLoaders;
  }
);

html = html.replace(
  'loadSeedShopCatalog(function () {\n        loadCropDefs(function () {\n          render();\n          resetViewport();\n        });\n      });',
  'loadSeedShopCatalog(function () {\n        loadCropDefs(function () {\n          render();\n          resetViewport();\n        });\n      });\n'
);

const banner =
  '<!-- agriculture-standalone.html — AUTO-GENERATED by tools/build-agriculture-standalone-html.mjs — 单文件可离线试玩，勿直接改此文件 -->\n';
if (!html.startsWith('<!-- agriculture-standalone')) {
  html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + banner);
}

fs.writeFileSync(OUT, html, 'utf8');
const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
console.log(
  'Wrote',
  OUT,
  '(' + kb + ' KB, seeds:',
  shopPayload.seeds.length + ', crops:',
  Object.keys(cropPayload.crops || {}).length + ')'
);
