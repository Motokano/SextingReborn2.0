import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildModularCatalog } from './item-attribute-catalog.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function validateBackpacks(c) {
  const assert = (v, message) => { if (!v) throw new Error('Backpack config: ' + message); };
  assert(c?.version === 1 && c.max_affixes === 2 && c.minimum_weight_factor > 0 && c.minimum_weight_factor <= 1, 'invalid version or limits');
  for (const [id, m] of Object.entries(c.models)) {
    assert(id.startsWith('eq_backpack_') && m.name && Number.isInteger(m.slots) && m.slots > 0 && Number.isFinite(m.weight_kg) && m.weight_kg > 0 && m.weight_factor > 0 && m.weight_factor <= 1, id);
  }
  for (const [id, x] of [...Object.entries(c.affixes), ...Object.entries(c.modifications)]) {
    assert(x.name && x.description, id + ' text');
    for (const key of ['self_factor', 'weight_factor', 'spoilage_factor']) if (key in x) assert(Number.isFinite(x[key]) && x[key] > 0 && x[key] <= 1, id + ' ' + key);
    if ('slots' in x) assert(Number.isSafeInteger(x.slots), id + ' slots');
    if ('added_weight' in x) assert(Number.isFinite(x.added_weight) && x.added_weight >= 0, id + ' mass');
    if (x.carry_class) assert(['mineral', 'equipment'].includes(x.carry_class), id + ' class');
  }
  for (const x of [...Object.values(c.models).map(m => m.craft), ...Object.values(c.modifications)]) {
    assert(x && Number.isSafeInteger(x.ticks) && x.ticks > 0 && Object.keys(x.cost || {}).length > 0, 'recipe');
    for (const n of Object.values(x.cost)) assert(Number.isSafeInteger(n) && n > 0, 'recipe quantity');
  }
  return c;
}
export function backpackTemplates(c) {
  validateBackpacks(c);
  return Object.fromEntries(Object.entries(c.models).map(([id, m]) => [id, {
    id, item_id: id, name: m.name, name_0: m.name, name_1: m.name, name_2: m.name,
    desc_0: m.description, desc_1: m.description, desc_2: m.description,
    category: 'equipment', sub_category: 'backpack', display_skill_id: 'survival_language',
    equip_slot: 'backpack', enchant_slots: c.max_affixes, weight_kg: m.weight_kg,
    backpack_slots: m.slots, backpack_weight_factor: m.weight_factor, stack_limit: 1, pocketable: false
  }]));
}
export function syncBackpackCatalog() {
  const read = p => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
  const writeText = (p, text) => { const file=path.join(root,p); if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==text) fs.writeFileSync(file,text); };
  const write = (p, v) => writeText(p, JSON.stringify(v, null, 2) + '\n');
  const c = validateBackpacks(read('data/backpacks.json'));
  const equipment = Object.assign(read('data/equipment.json'), backpackTemplates(c));
  write('data/equipment.json', equipment);
  write('data/equipment-catalog-v2.json', buildModularCatalog(equipment));
  const enchants = read('data/enchant.json');
  enchants._comment = enchants._comment.replace('每件装备有六个词条槽位', '装备词条槽位由模板决定（三款背包最多两条不同专属词条，其他装备沿用原上限）').replace('同一装备上多个词条之间效果相加（同类型数值相加）', '普通数值词条沿用同类型相加；背包减重和保鲜专属词条按剩余量乘算');
  for (const [id, a] of Object.entries(c.affixes)) enchants[id] = { id, name: a.name, description: a.description, effect_type: 'backpack', effect_params: Object.fromEntries(Object.entries(a).filter(([k]) => !['name', 'description'].includes(k))), applicable_slots: ['backpack'] };
  enchants._effect_types.backpack = '背包专属效果，按data/backpacks.json和BackpackSystem对剩余计重计算。';
  write('data/enchant.json', enchants);
  writeText('js/backpack-config.js', '/* Generated by tools/build-backpack-catalog.mjs; edit data/backpacks.json. */\nwindow.BackpackConfig = ' + JSON.stringify(c, null, 2) + ';\n');
  return c;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) syncBackpackCatalog();
