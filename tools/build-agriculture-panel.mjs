import {build} from 'esbuild';
import fs from 'node:fs';
const output='js/agriculture-panel.js';
const result=await build({entryPoints:['js/agriculture/panel.mjs'],bundle:true,write:false,format:'iife',target:'es2022',charset:'utf8',legalComments:'none',banner:{js:'// Generated by tools/build-agriculture-panel.mjs; edit js/agriculture/*.mjs.'}});
const content=result.outputFiles[0].text;
if(process.argv.includes('--check')){
 if(fs.readFileSync(output,'utf8')!==content)throw Error('Agriculture panel bundle is stale');
 console.log('Agriculture panel bundle is current');
}else{fs.writeFileSync(output,content);console.log('Built '+output);}
