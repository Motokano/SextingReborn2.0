/**
 * 打包海藻精设定说明为项目根单文件 HTML（无外部 fetch/script/link，file:// 可开）
 * 源稿：tools/seaweed-extract-design-overview.html
 * 用法：node tools/build-seaweed-extract-overview-html.mjs
 * 输出：seaweed-extract-design-standalone.html（项目根）
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(__dirname, 'seaweed-extract-design-overview.html');
const OUT = path.join(ROOT, 'seaweed-extract-design-standalone.html');

if (!fs.existsSync(SRC)) {
  console.error('Missing source:', SRC);
  process.exit(1);
}

let html = fs.readFileSync(SRC, 'utf8');

html = html.replace(/<title>[^<]*<\/title>/, '<title>海藻精设定说明 · 独立版</title>');
html = html.replace(
  /<p class="sub">[\s\S]*?<\/p>/,
  '<p class="sub">与 <code>docs/design/28-agriculture-irrigation.md</code> §4.3、§2.2d、§4b、§12.1、§15 对齐。非可玩 demo。'
    + ' · <strong>单文件离线</strong>（CSS/脚本/图示 SVG 均已内嵌；双击或 <code>file://</code> 可开，浓度与爆发试算可用）</p>'
);

const banner =
  '<!-- seaweed-extract-design-standalone.html — AUTO-GENERATED by tools/build-seaweed-extract-overview-html.mjs — 单文件可离线阅读，勿直接改此文件；改 tools/seaweed-extract-design-overview.html 后 npm run build:seaweed-extract-standalone -->\n';
if (!html.includes('seaweed-extract-design-standalone')) {
  html = html.replace(/<!DOCTYPE html>\s*/i, `<!DOCTYPE html>\n${banner}`);
}

// 移除旧版根目录非 standalone 产物，避免两份重复
const legacyOut = path.join(ROOT, 'seaweed-extract-design-overview.html');
if (fs.existsSync(legacyOut)) {
  try {
    fs.unlinkSync(legacyOut);
  } catch (_) { /* ignore */ }
}

fs.writeFileSync(OUT, html, 'utf8');
const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
console.log('Wrote', OUT, `(${kb} KB, standalone — no external deps)`);
