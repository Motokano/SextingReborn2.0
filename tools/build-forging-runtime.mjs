import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const bindings=read('data/forging/item-bindings-v1.json');
const balance=read('docs/design/examples/weapon-forging-balance-v1.json');
const traits=read('docs/design/examples/weapon-ore-intrinsic-traits-v1.json');
const materials=read('docs/design/examples/weapon-forging-material-requirements-v1.json');
const levels=read('tools/blade-forging/levels.json').levels;
const oreRows=[...read('docs/design/examples/weapon-forging-ores-v1.json').ores,...traits.oreAdditions];
const config={version:1,station:{mapId:'M0_Base_Inside_lv_1',x:5,y:11,npcId:'npc.station.forging_base',unlock:'forging_station_unlocked'},
 catalog:read('data/forging/item-catalog-v2.json'),bindings,balance,
 combinations:read('docs/design/examples/weapon-ore-combinations-v1.json'),
 ores:Object.fromEntries(oreRows.map(o=>[o.id,{id:o.id,scores:o.scores,trait:traits.intrinsicTraits.find(t=>t.oreId===o.id),processing:balance.ores.find(r=>r.id===o.id).processing}])),
 components:Object.fromEntries(Object.entries(bindings.components).map(([id,b])=>[id,{...b,itemId:id,...materials.components.find(p=>p.id===b.designId),costs:balance.components.find(p=>p.id===b.designId),board:levels.find(p=>p.id===b.designId)}]))};
const outputs={
 'js/forging-config.js':'/* Generated by tools/build-forging-runtime.mjs; edit the source tables. */\nwindow.ForgingConfig='+JSON.stringify(config)+';\n',
 'js/forging-board-core.js':'/* Generated from the tested playtest core; no separate rules fork. */\n(function(g){\n'+fs.readFileSync(path.join(root,'tools/blade-forging/core.mjs'),'utf8').replace('export function createBladeForge','function createBladeForge')+'\ng.createBladeForge=createBladeForge;\n})(window);\n',
 'js/forging-effects.js':fs.readFileSync(path.join(root,'tools/blade-forging/effects.js'),'utf8'),
 'js/forging-symbols.js':fs.readFileSync(path.join(root,'tools/blade-forging/symbols.js'),'utf8'),
 'css/forging-symbols.css':fs.readFileSync(path.join(root,'tools/blade-forging/symbols.css'),'utf8')
};
for(const [p,s] of Object.entries(outputs)){
 const target=path.join(root,p);
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==s)throw Error('Stale forging runtime: '+p);}
 else fs.writeFileSync(target,s);
}
console.log('Forging runtime: 83 parts, 12 ores, shared board rules and effects.');
