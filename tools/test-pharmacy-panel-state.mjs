import test from 'node:test';
import assert from 'node:assert/strict';
import { boot } from './ui-game-fixture.mjs';

for (const full of [false, true]) {
  for (const scenario of ['equipment', 'recipe names']) test(`pharmacy ${scenario} (${full ? 'Svelte' : 'native'})`, async () => {
    const h = await boot(full), g = h.g, d = g.document;
    try {
      let steps = 0;
      while (g.DialogueUI.isDialogueOpen() && steps++ < 1000) g.DialogueUI.next();
      await h.drain();
      g.SceneApp.openCharacterCreationAfterIntro();
      assert.equal(g.SceneApp.creation.confirm({ name: '制药界面回归', height: 178, gender: 'male', hand: 'right', leg: 'right' }), true);
      await h.drain();
      g.GameEngine.setState('M0_Base_Inside_lv_1', 13, 14);
      g.NPCSystem.setDemoFlag('npc_station_pharmacy_base_repaired', true);
      g.Survival.setState({ thirst: 100, dirtyness: 0 });
      const ps = g.PharmacyStation;
      const recipe = ps.getRecipes().find(r => r.recipe_id === 'life_pharmacy.crush_cannabis_powder');
      assert.ok(recipe);
      g.InventoryEquipment.setState({ ...g.InventoryEquipment.getState(), inventory_pocket: recipe.inputs.map(i => ({ item_id: i.item_id, count: i.count + 2 })) });
      ps.markRecipeKnown(recipe.recipe_id);
      ps.getState().installed_accessory_item_ids = ['tool_rolling_pin_pharmacy'];
      g.PharmacyStationPanel.open();
      await h.drain();
      assert.equal(g.PharmacyStationPanel.isOpen(), true);
      const methods = () => Array.from(d.querySelectorAll('#pharmacy-method-list button'), b => b.dataset.methodId);
      if (scenario === 'recipe names') {
        const button = d.querySelector('#pharmacy-known-list button');
        assert.ok(button);
        const name = g.StationCraftCore.getItemDisplayNameSafe(recipe.main_output.item_id);
        assert.ok(button.textContent.includes(name), button.textContent);
        assert.ok(button.textContent.includes('×' + recipe.main_output.count));
        assert.doesNotMatch(button.textContent, /life_pharmacy\.|pharmacy\.recipe\./);
        assert.equal(button.disabled, false);
        button.click();
        assert.equal(d.querySelector('#pharmacy-method-list button.active').dataset.methodId, recipe.method_id);
        assert.equal(Number(d.querySelector('#pharmacy-input-list input').value), recipe.inputs[0].count);
        const quantity = () => d.querySelector('#pharmacy-input-list input');
        const minus = () => d.querySelector('#pharmacy-input-list .pharmacy-quantity-step');
        const plus = () => d.querySelectorAll('#pharmacy-input-list .pharmacy-quantity-step')[1];
        plus().click();
        assert.equal(Number(quantity().value), recipe.inputs[0].count + 1);
        minus().click();
        assert.equal(Number(quantity().value), recipe.inputs[0].count);
        quantity().value = '999'; quantity().dispatchEvent(new g.Event('change', { bubbles: true }));
        assert.equal(Number(quantity().value), recipe.inputs[0].count + 2, 'quantity stays within available stock');
        assert.equal(plus().disabled, true);
        quantity().value = '0'; quantity().dispatchEvent(new g.Event('change', { bubbles: true }));
        assert.equal(Number(quantity().value), 1);
        assert.equal(minus().disabled, true);
        d.querySelector('#pharmacy-input-list .pharmacy-remove-input').click();
        assert.equal(quantity(), null);
        assert.equal(d.getElementById('pharmacy-clear-btn').disabled, true);
        button.click();
        ps.getState().installed_accessory_item_ids = [];
        g.PharmacyStationPanel.render();
        const locked = d.querySelector('#pharmacy-known-list button');
        assert.ok(locked, 'learned knowledge is preserved without its equipment');
        assert.equal(locked.disabled, true);
        assert.ok(locked.textContent.includes(g.StationCraftCore.getItemDisplayNameSafe('tool_rolling_pin_pharmacy')));
        button.click();
        assert.equal(d.querySelector('#pharmacy-method-list button.active'), null, 'stale recipe clicks cannot select hidden methods');
        assert.equal(d.getElementById('pharmacy-start-btn').disabled, true);
      } else {
        assert.deepEqual(methods(), ['life_pharmacy.crushing']);
        const stale = d.querySelector('#pharmacy-method-list button');
        stale.click();
        ps.getState().installed_accessory_item_ids.push('tool_mortar_pharmacy');
        g.PharmacyStationPanel.render();
        assert.deepEqual(methods(), ['life_pharmacy.blending', 'life_pharmacy.crushing']);
        ps.getState().installed_accessory_item_ids = ['tool_mortar_pharmacy'];
        g.PharmacyStationPanel.render();
        assert.deepEqual(methods(), ['life_pharmacy.blending']);
        assert.equal(d.querySelector('#pharmacy-method-list button.active'), null);
        stale.click();
        assert.equal(d.querySelector('#pharmacy-method-list button.active'), null);
        const state = g.InventoryEquipment.getState();
        g.InventoryEquipment.setState({ ...state, inventory_pocket: [{ item_id: 'tool_rolling_pin_pharmacy', count: 1 }] });
        g.PharmacyStationPanel.render();
        assert.deepEqual(methods(), ['life_pharmacy.blending'], 'carrying a tool does not install it');
        ps.getState().installed_accessory_item_ids = [];
        g.PharmacyStationPanel.render();
        assert.deepEqual(methods(), []);
        assert.match(d.getElementById('pharmacy-method-list').textContent, /装配/);
        assert.equal(d.getElementById('pharmacy-start-btn').disabled, true);
        const toggle = d.getElementById('pharmacy-equipment-toggle');
        const equipment = d.getElementById('pharmacy-equipment');
        const equipmentStatus = d.getElementById('pharmacy-equipment-status');
        assert.equal(toggle.textContent, '安装设备');
        assert.match(equipmentStatus.textContent, /尚未安装/);
        assert.equal(equipment.hidden, true);
        toggle.click();
        assert.equal(equipment.hidden, false);
        assert.equal(toggle.getAttribute('aria-expanded'), 'true');
        const install = d.querySelector('#pharmacy-available-accessories button');
        assert.ok(install);
        assert.match(d.getElementById('pharmacy-available-accessories').textContent, /木擀杖.*→ 粉碎/);
        install.click();
        assert.deepEqual(methods(), ['life_pharmacy.crushing']);
        assert.equal(toggle.textContent, '管理设备');
        assert.equal(equipmentStatus.textContent, '木擀杖');
        assert.match(d.getElementById('pharmacy-available-accessories').textContent, /背包中没有可安装的设备/);
        const installedStock = JSON.stringify(g.InventoryEquipment.getState());
        install.click();
        assert.equal(JSON.stringify(g.InventoryEquipment.getState()), installedStock, 'a stale install button cannot consume a second item');
        assert.equal(ps.getState().installed_accessory_item_ids.length, 1);
        d.querySelector('#pharmacy-accessory-list button').click();
        assert.equal(toggle.textContent, '安装设备');
        assert.deepEqual(methods(), []);
        assert.equal(g.InventoryHelpers.getInventoryCountByItemId('tool_rolling_pin_pharmacy'), 1);
        toggle.click();
        assert.equal(equipment.hidden, true);
        g.NPCSystem.setDemoFlag('pharmacy_injection_unlocked', true);
        g.PharmacyStationPanel.render();
        d.querySelectorAll('#pharmacy-mode-tabs button')[1].click();
        assert.equal(d.getElementById('pharmacy-equipment-section').hidden, true, 'injection mixing does not advertise unused equipment');
        d.querySelectorAll('#pharmacy-mode-tabs button')[0].click();
        assert.equal(d.getElementById('pharmacy-equipment-section').hidden, false);
      }
      assert.deepEqual(h.errors, []);
    } finally { await h.close(); }
  });
}
