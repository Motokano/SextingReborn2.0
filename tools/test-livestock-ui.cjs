const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert/strict');
const { chromium } = require('playwright');
const read = p => fs.readFileSync(path.join(__dirname, '..', p), 'utf8');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.setContent(read('index.html').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '').replace(/<link\b[^>]*>/gi, ''));
    await page.evaluate(strings => {
      window.UIText = { t: (k, v = {}) => (strings[k] || k).replace(/\{(\w+)\}/g, (_, n) => v[n] ?? '') };
      window.received = []; window.dropped = []; window.full = false;
      window.GameEngine = { getState: () => ({ mapId: 'test', x: 0, y: 0 }) };
      window.InventoryEquipment = { getSkillLevel: () => 50, putItemIntoDefaultContainer: it => { if (window.full) return { placed: false }; window.received.push(it); return { placed: true }; }, addItemToGround: (m,x,y,it) => window.dropped.push(it) };
    }, JSON.parse(read('data/ui_text_zhCN.json')));
    for (const file of ['js/livestock-state.js', 'js/livestock-panel.js']) await page.addScriptTag({ content: read(file) });
    await page.evaluate(({ species, modules, perks, costs, items }) => {
      LivestockState.setConfig(species.species, modules.modules, perks.perks, costs.costs, {}, species.pasture_rules);
      window.InventoryEquipment.getItemTemplate = id => items[id];
      LivestockState.initDemoState(); const st = LivestockState.getState(); st.power_charge = 10000;
      st.animals = ['cattle', 'sheep', 'pig', 'chicken', 'chicken'].map((id, i) => ({ uid: 'test_' + i, species_id: id, gender: 'female', weight_kg: species.species[id].growth.fatten_cap_kg, age_ticks: 100000, satiety: 90, hp: 100, perks: [], cooldowns: {}, dead: false, location_type: id === 'chicken' ? 'coop' : 'zone', zone_id: 'z' + (i % 4 + 1), arm_id: 'arm3', production_buffers: { egg: 1, milk: 1, wool: 1 } }));
      document.getElementById('modal-livestock').classList.add('show');
      LivestockPanel.init(); LivestockPanel.render();
    }, { species: JSON.parse(read('data/livestock-species.json')), modules: JSON.parse(read('data/livestock-modules.json')), perks: JSON.parse(read('data/livestock-perks.json')), costs: JSON.parse(read('data/livestock-build-costs.json')), items: JSON.parse(read('data/items.json')) });
    assert.equal(await page.locator('#livestock-overview-grid > *').count(), 9);
    assert.equal(await page.locator('#livestock-overview-grid .capacity-summary').count(), 0);
    const shot = async name => { const file = path.join(os.tmpdir(), 'livestock-ui-' + name + '.png'); await page.screenshot({ path: file, animations: 'disabled' }); console.log(file); };
    await shot('overview');
    await page.locator('[data-go-products]').click();
    assert.equal(await page.locator('[data-slaughter]').count(), 0);
    assert((await page.locator('.lv-product-head').innerText()).includes('4 份'));
    await shot('products');
    await page.locator('[data-routine-collect]').click();
    assert.equal(await page.evaluate(() => received.length), 4);
    assert.equal(await page.evaluate(() => LivestockState.getState().animals[0].hp), 100);
    assert(await page.locator('[data-routine-collect]').isDisabled());
    await page.evaluate(() => { window.full = true; LivestockState.getState().animals[3].production_buffers.egg = 1; LivestockPanel.render(); });
    await page.locator('[data-routine-collect]').click();
    assert.equal(await page.evaluate(() => dropped.length), 1);
    await page.locator('[data-product-mode="slaughter"]').click();
    assert.equal(await page.locator('[data-slaughter]').count(), 0);
    await page.locator('[data-slaughter-select="test_3"]').click();
    assert.equal(await page.locator('[data-slaughter]').count(), 1);
    assert.equal(await page.evaluate(() => LivestockState.getState().animals.length), 5);
    await page.evaluate(() => { const st = LivestockState.getState(); st.arm_zones = { arm1:['z2','z3'],arm2:['z3','z4'],arm3:['z4','z1'],arm4:['z1','z2'] }; LivestockPanel.setTab('overview'); });
    assert.equal(await page.locator('#livestock-overview-grid > :nth-child(2)').getAttribute('data-arm'), 'arm4');
    await page.evaluate(() => { LivestockState.getState().animals[1].hp = 60; LivestockPanel.setTab('animals'); });
    assert.equal(await page.locator('.animal-row').count(), 5);
    await page.locator('[data-animal-filter="chicken"]').click();
    assert.equal(await page.locator('.animal-row').count(), 2);
    await page.locator('[data-animal-filter="all"]').click();
    await page.locator('[data-attention-only]').click();
    assert.equal(await page.locator('.animal-row').count(), 1);
    assert((await page.locator('#livestock-animal-detail .detail-title').innerText()).includes('羊'));
    await page.locator('[data-attention-only]').click();
    await page.locator('.breeding-controls summary').click();
    await page.waitForFunction(() => document.querySelector('.breeding-controls').open);
    await page.evaluate(() => LivestockPanel.render());
    assert(await page.locator('.breeding-controls').evaluate(e => e.open));
    await page.locator('.lv-move-settings summary').click();
    await page.waitForFunction(() => document.querySelector('.lv-move-settings').open);
    await page.evaluate(() => LivestockPanel.render());
    assert(await page.locator('.lv-move-settings').evaluate(e => e.open));
    await page.locator('.lv-move-settings summary').click();
    await page.locator('.breeding-controls summary').click();
    await shot('animals');
    await page.evaluate(() => { const st = LivestockState.getState(); st.arms.arm4.cw_side = { module_id:'feed_trough', level:1, feed_units:30, occupied_slots:['cw_side'] }; LivestockPanel.setTab('overview'); });
    await page.locator('#livestock-overview-grid > :nth-child(2)').click();
    assert((await page.locator('.arm-card-title').innerText()).includes('四'));
    assert.equal(await page.locator('.lv-coverage-map .covered').count(), 2);
    assert((await page.locator('.lv-coverage-label').innerText()).includes('Z2'));
    await page.locator('[data-upgrade-preview="arm4|cw_side"]').click();
    assert((await page.locator('.lv-upgrade-preview').innerText()).includes('升级后'));
    assert.equal(await page.evaluate(() => LivestockState.getState().arms.arm4.cw_side.level), 1);
    await shot('modules');
    await page.evaluate(() => { LivestockState.getState().arms.arm4.bottom = { module_id:'coop', shadow:true }; LivestockPanel.render(); });
    await page.locator('.module-card[data-module="seeder"]').click();
    assert.equal(await page.locator('.empty-slot.mountable').count(), 0, 'a blocked shared slot must not be offered');
    await page.evaluate(() => { LivestockState.getState().arms.arm4.bottom = null; LivestockPanel.render(); });
    await page.locator('[data-select-arm="axis"]').click();
    assert.equal(await page.locator('.module-card[data-module="feed_trough"]').count(), 0);
    await page.locator('[data-select-arm="arm4"]').click();
    await page.setViewportSize({ width: 390, height: 844 });
    for (const tab of ['overview', 'products', 'animals', 'modules']) {
      await page.evaluate(t => LivestockPanel.setTab(t), tab);
      const overflow = await page.locator('.lv-view:not(.hidden)').evaluate(e => e.scrollWidth > e.clientWidth + 1);
      assert.equal(overflow, false, tab + ' must not clip horizontally');
      await shot('mobile-' + tab);
    }
    assert.deepEqual(errors, []);
    console.log('PASS layout, rotation mapping, routine collection, no blood loss, no duplicate claims, ground fallback, slaughter preview and narrow screens');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
