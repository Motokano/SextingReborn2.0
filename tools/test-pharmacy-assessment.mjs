import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const json=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const items=json('data/items.json');
const buffs=json('data/buffs.json').buffs;
const ctx={SceneCtx:{},InventoryEquipment:{getItemTemplate:id=>items[id],getState:()=>({}),setState(){}},BuffSystem:{getBuffTemplate:id=>buffs.find(b=>b.buff_id===id)}};
vm.createContext(ctx);
for(const f of ['pharmacy-config','pharmacy-compounding'])vm.runInContext(fs.readFileSync('js/'+f+'.js','utf8'),ctx);
const pc=ctx.PharmacyCompounding;
pc.setConfig(ctx.PharmacyConfig.parseCsv(fs.readFileSync('data/pharmacy-system-config.csv','utf8')),json('data/pharmacy-conflict-rules.json'));
const rows=(...ids)=>ids.map(item_id=>({item_id,count:1}));
const mix=rows('solvent_water_pure','med_cocaine_powder','adj_vitamin_c','med_vitamin_c_powder');
assert(pc.resolve(mix).conflicts.length>0);
for(const level of [0,1]){
 const a=pc.assess(mix,level);assert.equal(a.conflicts.length,0);assert.equal(a.net_toxicity,null);assert.equal(a.effects.length,0);
}
assert(pc.assess(mix,0).visible_abnormality);
assert.equal(pc.assess(mix,0).salt,null);
assert(pc.assess(mix,1).salt);
assert.equal(pc.assess(mix,2).conflicts[0].outcome,null);
assert(pc.assess(mix,2).effects.length);
assert.equal(pc.assess(mix,2).effects[0].detail,null);
assert(pc.assess(mix,4).conflicts[0].outcome);
assert.equal(typeof pc.assess(mix,4).net_toxicity,'number');
assert.equal(pc.assess(mix,6).conflicts[0].suggestion,'separate');
const solvent=rows('solvent_glucose_solution','med_rehydration_powder');
assert.equal(pc.assess(solvent,0).conflicts.length,0);
assert.equal(pc.assess(solvent,1).conflicts.length,1);
const complex=rows('solvent_water_pure','med_liver_herb_powder','med_vitamin_c_powder');
assert(pc.resolve(complex).conflicts.some(c=>c.rule_id==='acid_glycoside'));
assert.equal(pc.assess(complex,4).conflicts.length,0);
assert(pc.assess(complex,6).conflicts.length);
const key=pc.compoundIdentityKey(pc.normalizeInputs(mix));
assert.equal(key,pc.compoundIdentityKey([...mix].reverse()));
assert.equal(typeof pc.getHistory,'undefined');
ctx.GameTime={getState:()=>({totalTicks:0}),reset(){}};
ctx.GameEngine={getState:()=>({mapId:'home',x:0,y:0}),setState(){}};
ctx.CharacterAttributes={getState:()=>({}),setState(){},recalcCharacterStats(){}};
ctx.Survival={getState:()=>({}),setState(){}};
vm.runInContext(fs.readFileSync('js/save-system.js','utf8'),ctx);
const snap=ctx.SaveSystem.buildSnapshotForDebug();
assert.equal(snap.player.sceneUi.pharmacy_compound_history,undefined);
assert(ctx.SaveSystem.applySnapshotForDebug(snap));
console.log('pharmacy assessment: level boundaries, visible clues, stable formula identity and no persisted history passed');
