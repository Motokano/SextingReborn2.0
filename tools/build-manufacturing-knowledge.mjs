// Runtime knowledge index only; crafting costs and execution remain in their own systems.
import fs from 'node:fs';
const source='docs/design/examples/manufacturing-system-v1.json';
const data=JSON.parse(fs.readFileSync(source,'utf8'));
const recipes=data.recipes.map(r=>({id:r.recipe_id,itemId:r.item_id,name:r.name,unlock:r.unlock.kind,skillId:r.unlock.skill_id||null,level:r.unlock.level||null}));
if(new Set(recipes.map(r=>r.id)).size!==recipes.length)throw Error('Duplicate recipe ID');
const text='/* Generated by tools/build-manufacturing-knowledge.mjs; do not edit. */\nglobalThis.ManufacturingKnowledgeCatalog='+JSON.stringify({source,revision:data.review_revision,recipes})+';\n';
const file='js/manufacturing-knowledge-catalog.js';
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n')!==text)throw Error('Manufacturing knowledge catalog is stale');}
else fs.writeFileSync(file,text);
console.log(`Manufacturing knowledge: ${recipes.length} recipes, ${recipes.filter(r=>r.unlock==='exploration').length} research recipes`);
