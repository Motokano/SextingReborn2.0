      6:['.#####.','#######','.#####.','...#...','..###..','..###..'],
      7:['...#...','..###..','...#...','...#...','..###..','.#####.','..###..'],
      8:['.#.#.#.','.#####.','..###..','...#...','..###..','..###..'],
