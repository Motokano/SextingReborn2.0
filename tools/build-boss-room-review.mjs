// Keep the review document in sync with the real app without about:srcdoc.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const source=fs.readFileSync('index.html','utf8');
const output=source.replace('<head>','<head>\n<!-- Generated by tools/build-boss-room-review.mjs; edit the source, not this file. -->\n<base href="../">\n<script src="tools/street-thug-boss-room-memory.js"></script>\n<link rel="stylesheet" href="tools/street-thug-boss-room-frame.css">')
 .replace(/<link\b[^>]*href="https:\/\/fonts\.googleapis\.com[^>]*>/g,'');
const target='tools/street-thug-boss-room-game.html';
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8'),output,'rebuild the isolated review document after index.html changes');
else fs.writeFileSync(target,output);
console.log('Isolated room review document '+(process.argv.includes('--check')?'matches':'built from')+' index.html.');
